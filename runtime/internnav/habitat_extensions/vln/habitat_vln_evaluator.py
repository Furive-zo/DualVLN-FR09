        if getattr(self.model_args, 'mode', '') == 'register_vln':
            _real_env = self.env
            _last_obs = [None]  # mutable cell

            class _NoTiltEnv:
                def __getattr__(self, name):
                    return getattr(_real_env, name)
                def step(self, action):
                    if action in (action_code.LOOKUP, action_code.LOOKDOWN):
                        obs = _last_obs[0]
                        return obs, 0.0, False, {}
                    result = _real_env.step(action)
                    _last_obs[0] = result[0] if isinstance(result, tuple) else result
                    return result
                def reset(self):
                    obs = _real_env.reset()
                    _last_obs[0] = obs
                    return obs
                def get_metrics(self):
                    return _real_env.get_metrics()
                def get_current_episode(self):
                    return _real_env.get_current_episode()
                @property
                def is_running(self):
                    return _real_env.is_running
                @property
                def episodes(self):
                    return _real_env.episodes

            self.env = _NoTiltEnv()

